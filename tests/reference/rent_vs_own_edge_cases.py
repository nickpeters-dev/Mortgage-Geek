"""
Expected values for tests/rentVsOwn.test.mjs, written to
tests/reference/rent_vs_own_edge_cases.json.

Two independent sources, neither of which is the JavaScript simulation:

1. "reference": the existing Python reference model
   (scripts/rent_vs_own_reference.py, imported unchanged) run at edge-case
   inputs the six parity fixtures do not reach. Conventional loans only, which
   is all the reference models.

2. "closed_form": scenarios simple enough to solve with a formula instead of a
   month-by-month loop, computed with exact decimal arithmetic:
     - Rent so high that owning is cheaper every month: the renter never adds
       to the portfolio, so it is just the starting cash compounding monthly.
     - Rent so low that renting is cheaper every month: the owner's side fund
       stays at zero, so owner wealth is home value net of selling costs minus
       the loan balance, with the balance from the standard formula.

Run from the repo root:  python3 tests/reference/rent_vs_own_edge_cases.py
"""
import json
import os
import sys
from decimal import Decimal as D, getcontext

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "scripts"))
from rent_vs_own_reference import sim, breakeven  # noqa: E402

getcontext().prec = 50

# The live tool's defaults (src/components/rentVsOwnSim.js DEFAULTS), restated
# here as plain numbers so this file does not read the JavaScript.
JS_DEFAULTS = dict(price=350000, downPct=3.5, rent0=2000, rate=6.75, rentG=4.1, homeG=5.0, inv=10,
                   taxPct=0.95, insPct=0.35, ccPct=3, sellPct=7, maintRate=1, costGrowth=3, renterIns=20)

YEARS = [0, 1, 2, 5, 10, 15, 20, 30]


def pmi_rate(down_pct):
    # The site's published Conventional PMI estimate, by down payment tier.
    if down_pct >= 20:
        return 0.0
    if down_pct >= 10:
        return 0.0027
    if down_pct >= 5:
        return 0.0037
    return 0.0052


def run_reference(overrides):
    s = dict(JS_DEFAULTS, **overrides)
    rows, pmt = sim(price=s["price"], dp_pct=s["downPct"] / 100, rate=s["rate"] / 100, rent0=s["rent0"],
                    rent_g=s["rentG"] / 100, hv_g=s["homeG"] / 100, inv_g=s["inv"] / 100,
                    cc_pct=s["ccPct"] / 100, sell_pct=s["sellPct"] / 100,
                    tax_rate=s["taxPct"] / 100, ins_rate=s["insPct"] / 100,
                    pmi_rate=pmi_rate(s["downPct"]),
                    maint_rate=s["maintRate"] / 100, cost_growth=s["costGrowth"] / 100, renter_ins=s["renterIns"])
    return dict(
        inputs=overrides,
        payment=round(pmt, 2),
        breakeven=breakeven(rows),
        rows={str(y): dict(owner=round(rows[y]["owner"]), renter=round(rows[y]["renter"]),
                           balance=round(rows[y]["bal"]), side=round(rows[y]["side"])) for y in YEARS},
    )


REFERENCE_CASES = {
    "zero_appreciation": dict(homeG=0),
    "nothing_grows": dict(homeG=0, rentG=0, costGrowth=0),
    "rent_far_below_owning": dict(rent0=800),
    "rent_far_above_owning": dict(rent0=6000),
    "rate_at_minimum": dict(rate=3),
    "rate_at_maximum": dict(rate=10),
    "down_payment_minimum": dict(downPct=3),
    "down_payment_maximum": dict(downPct=50),
    "investment_return_minimum": dict(inv=4),
    "investment_return_maximum": dict(inv=12),
    "max_selling_cost_no_closing_cost": dict(sellPct=12, ccPct=0),
    "price_at_minimum": dict(price=50000, rent0=600),
    "price_at_maximum": dict(price=2000000, rent0=9000),
}


def closed_form():
    price, down_pct, rate, inv, cc, sell, home_g = D(350000), D("3.5"), D("6.75"), D(10), D(3), D(7), D(5)
    down = price * down_pct / 100
    loan = price - down
    start_cash = down + price * cc / 100
    i = rate / 100 / 12
    n = 360
    pmt = loan * i / (1 - (1 + i) ** (-n))
    im = inv / 100 / 12

    def balance(months):
        return loan * (1 + i) ** months - pmt * ((1 + i) ** months - 1) / i

    out = dict(start_cash=float(start_cash), loan=float(loan), payment=float(round(pmt, 2)),
               renter_untouched={}, owner_no_side_fund={})
    for y in YEARS:
        out["renter_untouched"][str(y)] = float(round(start_cash * (1 + im) ** (12 * y), 2))
        hv = price * (1 + home_g / 100) ** y
        bal = balance(12 * y) if y < 30 else D(0)
        out["owner_no_side_fund"][str(y)] = float(round(hv * (1 - sell / 100) - bal, 2))
    return out


if __name__ == "__main__":
    data = dict(
        note="Generated by tests/reference/rent_vs_own_edge_cases.py. Do not edit by hand.",
        defaults=JS_DEFAULTS,
        years=YEARS,
        reference={name: run_reference(o) for name, o in REFERENCE_CASES.items()},
        closed_form=closed_form(),
    )
    path = os.path.join(HERE, "rent_vs_own_edge_cases.json")
    with open(path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    for name, c in data["reference"].items():
        r10 = c["rows"]["10"]
        print(f"{name:36} breakeven {str(c['breakeven']):>4}  y10 owner {r10['owner']:>10,} renter {r10['renter']:>10,} side {r10['side']:>9,}")
    print("closed form:", {k: v for k, v in data["closed_form"].items() if not isinstance(v, dict)})
